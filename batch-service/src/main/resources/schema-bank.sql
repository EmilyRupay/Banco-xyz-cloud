-- ============================================================
-- Tablas de negocio del batch-service (las tablas BATCH_* de Spring Batch se crean automaticamente)
-- Compatible con PostgreSQL (produccion) y H2 (pruebas)
-- ============================================================

-- Registros que no superan las reglas de calidad (auditoria de los 3 procesos)
CREATE TABLE IF NOT EXISTS bt_registro_rechazado (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job            VARCHAR(20)  NOT NULL,
    clave_proceso  VARCHAR(20)  NOT NULL,
    linea          INTEGER      NOT NULL,
    motivo         VARCHAR(30)  NOT NULL,
    detalle        VARCHAR(255),
    contenido      VARCHAR(500),
    registrado_en  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_rechazo_job ON bt_registro_rechazado (job, clave_proceso);

-- ---------- Job 1: Reporte de Transacciones Diarias ----------
CREATE TABLE IF NOT EXISTS bt_transaccion_diaria (
    fecha_proceso  VARCHAR(10)   NOT NULL,
    linea          INTEGER       NOT NULL,
    id_origen      BIGINT        NOT NULL,
    fecha          DATE          NOT NULL,
    tipo           VARCHAR(10)   NOT NULL,
    monto          NUMERIC(15,2) NOT NULL,
    alerta         VARCHAR(30),
    alerta_detalle VARCHAR(255),
    PRIMARY KEY (fecha_proceso, linea)
);

CREATE TABLE IF NOT EXISTS bt_resumen_diario (
    fecha_proceso  VARCHAR(10)   NOT NULL,
    fecha          DATE          NOT NULL,
    cantidad       INTEGER       NOT NULL,
    total_creditos NUMERIC(15,2) NOT NULL,
    total_debitos  NUMERIC(15,2) NOT NULL,
    neto           NUMERIC(15,2) NOT NULL,
    alertas        INTEGER       NOT NULL,
    PRIMARY KEY (fecha_proceso, fecha)
);

-- ---------- Job 2: Calculo de Intereses Mensuales ----------
CREATE TABLE IF NOT EXISTS bt_cuenta_staging (
    periodo    VARCHAR(7)    NOT NULL,
    linea      INTEGER       NOT NULL,
    cuenta_id  BIGINT        NOT NULL,
    nombre     VARCHAR(100)  NOT NULL,
    saldo      NUMERIC(15,2) NOT NULL,
    edad       INTEGER       NOT NULL,
    tipo       VARCHAR(10)   NOT NULL,
    PRIMARY KEY (periodo, cuenta_id)
);

CREATE TABLE IF NOT EXISTS bt_interes_mensual (
    periodo       VARCHAR(7)    NOT NULL,
    cuenta_id     BIGINT        NOT NULL,
    nombre        VARCHAR(100)  NOT NULL,
    tipo          VARCHAR(10)   NOT NULL,
    saldo_inicial NUMERIC(15,2) NOT NULL,
    tasa_mensual  NUMERIC(12,8) NOT NULL,
    interes       NUMERIC(15,2) NOT NULL,
    saldo_final   NUMERIC(15,2) NOT NULL,
    naturaleza    VARCHAR(10)   NOT NULL,
    PRIMARY KEY (periodo, cuenta_id)
);

-- ---------- Job 3: Estados de Cuenta Anuales ----------
CREATE TABLE IF NOT EXISTS bt_movimiento_anual (
    anio        INTEGER       NOT NULL,
    linea       INTEGER       NOT NULL,
    cuenta_id   BIGINT        NOT NULL,
    fecha       DATE          NOT NULL,
    tipo        VARCHAR(10)   NOT NULL,
    monto       NUMERIC(15,2) NOT NULL,
    descripcion VARCHAR(255)  NOT NULL,
    PRIMARY KEY (anio, linea)
);
CREATE INDEX IF NOT EXISTS idx_mov_anual_cuenta ON bt_movimiento_anual (anio, cuenta_id);

CREATE TABLE IF NOT EXISTS bt_estado_cuenta_anual (
    anio                 INTEGER       NOT NULL,
    cuenta_id            BIGINT        NOT NULL,
    cantidad_movimientos INTEGER       NOT NULL,
    total_depositos      NUMERIC(15,2) NOT NULL,
    total_retiros        NUMERIC(15,2) NOT NULL,
    total_compras        NUMERIC(15,2) NOT NULL,
    total_pagos          NUMERIC(15,2) NOT NULL,
    saldo_neto           NUMERIC(15,2) NOT NULL,
    primer_movimiento    DATE          NOT NULL,
    ultimo_movimiento    DATE          NOT NULL,
    PRIMARY KEY (anio, cuenta_id)
);
